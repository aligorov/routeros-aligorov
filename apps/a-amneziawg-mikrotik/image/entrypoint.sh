#!/bin/sh
set -eu

ensure_tun() {
    if [ ! -c /dev/net/tun ]; then
        printf '[entrypoint] Creating /dev/net/tun...\n'
        mkdir -p /dev/net
        if ! mknod /dev/net/tun c 10 200; then
            printf '[entrypoint] ERROR: Failed to create /dev/net/tun\n' >&2
            exit 1
        fi
    fi
    if ! exec 3<>/dev/net/tun 2>/dev/null; then
        printf '[entrypoint] ERROR: Cannot open /dev/net/tun\n' >&2
        exit 1
    fi
    exec 3>&-
}

fix_resolvconf() {
    [ -e /etc/resolv.conf ] || return 0
    [ -w /etc/resolv.conf ] || return 0
    if [ ! -s /etc/resolv.conf ]; then
        printf '# Generated by resolvconf\n' > /etc/resolv.conf || true
    elif ! grep -q '^# Generated by resolvconf' /etc/resolv.conf; then
        tmp="/tmp/resolv.conf.$$"
        { printf '# Generated by resolvconf\n'; cat /etc/resolv.conf; } > "$tmp" && \
            cat "$tmp" > /etc/resolv.conf || true
        rm -f "$tmp"
    fi
}

fix_ip_rules() {
    ip -4 rule show | awk '
        /from all lookup main$/ && $1+0 < 32766 {gsub(":", "", $1); print $1}
        /from all lookup default$/ && $1+0 < 32767 {gsub(":", "", $1); print $1}
    ' | while read -r prio; do
        [ -n "$prio" ] && ip -4 rule del priority "$prio" 2>/dev/null || true
    done
    ip -4 rule show | grep -q 'from all lookup main' || ip -4 rule add lookup main priority 32766 || true
    ip -4 rule show | grep -q 'from all lookup default' || ip -4 rule add lookup default priority 32767 || true

    ip -6 rule show 2>/dev/null | awk '
        /from all lookup main$/ && $1+0 < 32766 {gsub(":", "", $1); print $1}
        /from all lookup default$/ && $1+0 < 32767 {gsub(":", "", $1); print $1}
    ' | while read -r prio; do
        [ -n "$prio" ] && ip -6 rule del priority "$prio" 2>/dev/null || true
    done
    ip -6 rule show 2>/dev/null | grep -q 'from all lookup main' || ip -6 rule add lookup main priority 32766 2>/dev/null || true
    ip -6 rule show 2>/dev/null | grep -q 'from all lookup default' || ip -6 rule add lookup default priority 32767 2>/dev/null || true
}

detect_lan_iface() {
    if [ -n "${AWG_LAN_IFACE:-}" ]; then
        printf '%s\n' "$AWG_LAN_IFACE"
        return 0
    fi
    iface=$(ip -o -4 route show default 2>/dev/null | awk '{for(i=1;i<=NF;i++) if($i=="dev"){print $(i+1); exit}}')
    if [ -z "$iface" ]; then
        iface=$(ip -o link show | awk -F': ' '$2 != "lo" {sub(/@.*/, "", $2); print $2; exit}')
    fi
    printf '%s\n' "$iface"
}

ensure_tun
fix_resolvconf
if [ -z "${AWG_LAN_IFACE:-}" ]; then
    AWG_LAN_IFACE=$(detect_lan_iface)
    export AWG_LAN_IFACE
fi
printf '[entrypoint] Detected veth interface: %s\n' "${AWG_LAN_IFACE:-none}"

sysctl -w net.ipv4.ip_forward=1 >/dev/null 2>&1 || printf '[entrypoint] WARN: could not set net.ipv4.ip_forward=1\n'
if [ "${AWG_ENABLE_IPV6:-on}" = "on" ]; then
    # Set disable_ipv6=0 and accept_ra=2 BEFORE enabling forwarding=1 so Linux does not flush existing RA routes.
    sysctl -w net.ipv6.conf.all.disable_ipv6=0 >/dev/null 2>&1 || true
    sysctl -w net.ipv6.conf.default.disable_ipv6=0 >/dev/null 2>&1 || true
    sysctl -w net.ipv6.conf.all.accept_ra=2 >/dev/null 2>&1 || true
    sysctl -w net.ipv6.conf.default.accept_ra=2 >/dev/null 2>&1 || true
    if [ -n "${AWG_LAN_IFACE:-}" ] && [ "${AWG_LAN_IFACE}" != "none" ]; then
        sysctl -w "net.ipv6.conf.${AWG_LAN_IFACE}.disable_ipv6=0" >/dev/null 2>&1 || true
        sysctl -w "net.ipv6.conf.${AWG_LAN_IFACE}.accept_ra=2" >/dev/null 2>&1 || true
        sysctl -w "net.ipv6.conf.${AWG_LAN_IFACE}.accept_ra_defrtr=1" >/dev/null 2>&1 || true
        sysctl -w "net.ipv6.conf.${AWG_LAN_IFACE}.accept_ra_rt_info_max_plen=64" >/dev/null 2>&1 || true
    fi
    sysctl -w net.ipv6.conf.all.forwarding=1 >/dev/null 2>&1 || true
    sysctl -w net.ipv6.conf.default.forwarding=1 >/dev/null 2>&1 || true
else
    sysctl -w net.ipv6.conf.all.forwarding=0 >/dev/null 2>&1 || true
    sysctl -w net.ipv6.conf.all.disable_ipv6=1 >/dev/null 2>&1 || true
    sysctl -w net.ipv6.conf.default.disable_ipv6=1 >/dev/null 2>&1 || true
fi
fix_ip_rules

if [ "${AWG_ENABLE_IPV6:-on}" = "on" ] && [ -n "${AWG_LAN_IFACE:-}" ] && [ "${AWG_LAN_IFACE}" != "none" ]; then
    # Dynamic Dual-Stack: if LAN interface lacks a global/ULA IPv6, derive ULA fallback from IPv4
    # Use metric 2048 so any native RouterOS RA/SLAAC route (metric 1024) automatically takes precedence.
    if ! ip -6 -o addr show dev "${AWG_LAN_IFACE}" scope global 2>/dev/null | grep -q 'inet6'; then
        v4_cidr=$(ip -o -4 addr show dev "${AWG_LAN_IFACE}" 2>/dev/null | awk '{print $4; exit}')
        v4_gw=$(ip -o -4 route show default dev "${AWG_LAN_IFACE}" 2>/dev/null | awk '{for(i=1;i<=NF;i++) if($i=="via"){print $(i+1); exit}}')
        if [ -n "$v4_cidr" ] && [ -n "$v4_gw" ]; then
            v4_ip="${v4_cidr%%/*}"
            o1=$(printf '%s' "$v4_ip" | cut -d. -f1)
            o2=$(printf '%s' "$v4_ip" | cut -d. -f2)
            o3=$(printf '%s' "$v4_ip" | cut -d. -f3)
            o4=$(printf '%s' "$v4_ip" | cut -d. -f4)
            gw_o4=$(printf '%s' "$v4_gw" | cut -d. -f4)
            ula_ip="fd00:${o1}:${o2}:${o3}::${o4}/64"
            ula_gw="fd00:${o1}:${o2}:${o3}::${gw_o4}"
            ip -6 addr add "$ula_ip" dev "${AWG_LAN_IFACE}" 2>/dev/null || true
            ip -6 route add default via "$ula_gw" dev "${AWG_LAN_IFACE}" metric 2048 2>/dev/null || true
            printf '[entrypoint] Auto-configured dynamic ULA IPv6 fallback: %s via %s\n' "$ula_ip" "$ula_gw"
        fi
    fi
fi

exec /usr/bin/awg-ctl
