#!/bin/sh
set -eu

CONFIG_MODE="${CONFIG_MODE:-env}"
CONFIG_PATH="${CONFIG_PATH:-/app/config/config.yaml}"

mkdir -p /app/config /app/data /app/keys /app/certs

# Handle API token (auto-generate persistent >= 16-char token if set to auto)
API_TOKEN="${RELAY_API_TOKEN:-auto}"
if [ "$API_TOKEN" = "auto" ] || [ -z "$API_TOKEN" ]; then
    TOKEN_FILE="/app/keys/.api_token"
    if [ -s "$TOKEN_FILE" ]; then
        API_TOKEN="$(tr -d ' \r\n' < "$TOKEN_FILE")"
    else
        API_TOKEN="$(od -An -tx1 -N16 /dev/urandom | tr -d ' \n')"
        printf '%s\n' "$API_TOKEN" > "$TOKEN_FILE"
        chmod 600 "$TOKEN_FILE"
        echo "[ligament-relay] Generated API token saved to $TOKEN_FILE"
    fi
fi
export RELAY_API_TOKEN="$API_TOKEN"

# Handle HOST_IP
if [ "${RELAY_HOST_IP:-auto}" = "auto" ]; then
    unset RELAY_HOST_IP 2>/dev/null || true
fi

# YAML single-quote helper
yaml_sq() {
    printf "%s" "$1" | sed "s/'/''/g"
}

if [ "$CONFIG_MODE" = "env" ] || [ ! -f "$CONFIG_PATH" ]; then
    RELAY_ID_VAL="$(yaml_sq "${RELAY_ID:-branch-routeros}")"
    RELAY_NAME_VAL="$(yaml_sq "${RELAY_NAME:-RouterOS Branch}")"
    MAX_OFFLINE_TTL_VAL="$(yaml_sq "${RELAY_MAX_OFFLINE_TTL:-72h}")"
    CORE_URL_VAL="$(yaml_sq "${CORE_URL:-https://2fa.example.com}")"
    CORE_INSECURE_VAL="${CORE_INSECURE_SKIP_VERIFY:-false}"
    CORE_ALLOW_INSECURE_VAL="${CORE_ALLOW_INSECURE:-false}"

    CORE_CA_VAL="${CORE_CA_FILE:-}"
    if [ -z "$CORE_CA_VAL" ] && [ -f /app/certs/core-ca.pem ]; then
        CORE_CA_VAL="/app/certs/core-ca.pem"
    fi

    RADIUS_ENABLED_VAL="${RADIUS_ENABLED:-true}"
    RADIUS_TRUST_DAYS_VAL="${RADIUS_TRUST_DAYS:-7}"
    RADIUS_REQ_MA_VAL="${RADIUS_REQUIRE_MSG_AUTH:-true}"
    RADIUS_VERIFY_NAS_VAL="${RADIUS_VERIFY_NAS_IP:-false}"

    LDAP_ENABLED_VAL="${LDAP_ENABLED:-true}"
    LDAP_URL_VAL="$(yaml_sq "${LDAP_URL:-ldaps://dc01.example.local:636}")"
    LDAP_BASE_DN_VAL="$(yaml_sq "${LDAP_BASE_DN:-DC=example,DC=local}")"
    LDAP_BIND_DN_VAL="$(yaml_sq "${LDAP_BIND_DN:-CN=svc_2fa,OU=Service Accounts,DC=example,DC=local}")"
    LDAP_USER_FILTER_VAL="$(yaml_sq "${LDAP_USER_FILTER:-(sAMAccountName=%s)}")"
    LDAP_INSECURE_VAL="${LDAP_INSECURE_SKIP_VERIFY:-false}"

    LDAP_CA_VAL="${LDAP_CA_FILE:-}"
    if [ -z "$LDAP_CA_VAL" ] && [ -f /app/certs/ad-ca.pem ]; then
        LDAP_CA_VAL="/app/certs/ad-ca.pem"
    fi

    HTTP_TLS_CERT_VAL="${HTTP_TLS_CERT:-}"
    HTTP_TLS_KEY_VAL="${HTTP_TLS_KEY:-}"
    if [ -z "$HTTP_TLS_CERT_VAL" ] && [ -z "$HTTP_TLS_KEY_VAL" ] && [ -f /app/certs/relay-cert.pem ] && [ -f /app/certs/relay-key.pem ]; then
        HTTP_TLS_CERT_VAL="/app/certs/relay-cert.pem"
        HTTP_TLS_KEY_VAL="/app/certs/relay-key.pem"
    fi

    DISCOVERY_ENABLED_VAL="${DISCOVERY_ENABLED:-true}"
    DISCOVERY_PORT_VAL="${DISCOVERY_PORT:-8082}"

    {
        echo "# Generated by RouterOS entrypoint (CONFIG_MODE=${CONFIG_MODE})"
        echo "relay:"
        echo "  id: '${RELAY_ID_VAL}'"
        echo "  name: '${RELAY_NAME_VAL}'"
        if [ -n "${RELAY_HOST_IP:-}" ]; then
            echo "  host_ip: '$(yaml_sq "$RELAY_HOST_IP")'"
        fi
        echo "  max_offline_ttl: '${MAX_OFFLINE_TTL_VAL}'"
        echo ""
        echo "core:"
        echo "  url: '${CORE_URL_VAL}'"
        echo "  password: \"\${RELAY_CORE_PASSWORD}\""
        if [ -n "$CORE_CA_VAL" ]; then
            echo "  ca_file: '$(yaml_sq "$CORE_CA_VAL")'"
        fi
        echo "  insecure_skip_verify: ${CORE_INSECURE_VAL}"
        echo "  allow_insecure: ${CORE_ALLOW_INSECURE_VAL}"
        echo ""
        echo "storage:"
        echo "  path: /app/data/relay.db"
        echo "  key_file: /app/keys/relay.key"
        echo ""
        echo "radius:"
        echo "  enabled: ${RADIUS_ENABLED_VAL}"
        echo "  listen: \":1812\""
        echo "  secret: \"\${RELAY_RADIUS_SECRET}\""
        echo "  trust_days: ${RADIUS_TRUST_DAYS_VAL}"
        echo "  trust_bind_nas: true"
        echo "  require_message_authenticator: ${RADIUS_REQ_MA_VAL}"
        echo "  verify_nas_ip: ${RADIUS_VERIFY_NAS_VAL}"
        echo ""
        echo "ldap:"
        echo "  enabled: ${LDAP_ENABLED_VAL}"
        echo "  url: '${LDAP_URL_VAL}'"
        echo "  base_dn: '${LDAP_BASE_DN_VAL}'"
        echo "  bind_dn: '${LDAP_BIND_DN_VAL}'"
        echo "  bind_password: \"\${RELAY_LDAP_PASSWORD}\""
        echo "  user_filter: '${LDAP_USER_FILTER_VAL}'"
        if [ -n "$LDAP_CA_VAL" ]; then
            echo "  ca_file: '$(yaml_sq "$LDAP_CA_VAL")'"
        fi
        echo "  insecure_skip_verify: ${LDAP_INSECURE_VAL}"
        echo ""
        echo "http:"
        echo "  listen: \":8082\""
        echo "  api_token: \"\${RELAY_API_TOKEN}\""
        echo "  tls:"
        echo "    cert: '$(yaml_sq "$HTTP_TLS_CERT_VAL")'"
        echo "    key: '$(yaml_sq "$HTTP_TLS_KEY_VAL")'"
        echo ""
        echo "discovery:"
        echo "  enabled: ${DISCOVERY_ENABLED_VAL}"
        echo "  port: ${DISCOVERY_PORT_VAL}"
        if [ -n "${BASTION_ALLOW_CIDRS:-}" ]; then
            echo ""
            echo "bastion:"
            echo "  allow_cidrs:"
            OLD_IFS="$IFS"
            IFS=','
            for cidr in $BASTION_ALLOW_CIDRS; do
                trimmed="$(printf "%s" "$cidr" | tr -d ' \t')"
                if [ -n "$trimmed" ]; then
                    echo "    - '$(yaml_sq "$trimmed")'"
                fi
            done
            IFS="$OLD_IFS"
        fi
    } > "$CONFIG_PATH"
    echo "[ligament-relay] Generated $CONFIG_PATH (mode=$CONFIG_MODE)"
fi

chown -R relay:relay /app/config /app/data /app/keys /app/certs
chmod 700 /app/data /app/keys
chmod 600 "$CONFIG_PATH" 2>/dev/null || true
chmod 600 /app/keys/.api_token /app/keys/relay.key 2>/dev/null || true

export CONFIG_PATH
exec su -s /bin/sh relay -c 'exec /app/relay -config "$CONFIG_PATH"'
